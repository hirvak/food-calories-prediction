"""
Reports/_pdf_common.py

Shared ReportLab building blocks (colors, paragraph styles, table styling,
footer/page numbers) reused by pdf_report.py and admin_pdf_report.py so the
"NutriLens blue theme" and layout stay consistent without duplicating code.
"""

from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.platypus import Table, TableStyle
from reportlab.graphics.shapes import Drawing, Polygon

# ---------- brand palette ----------

PRIMARY_BLUE = colors.HexColor("#2563EB")
SUCCESS_GREEN = colors.HexColor("#10B981")
LIGHT_BG = colors.HexColor("#F8FAFC")
BORDER_COLOR = colors.HexColor("#E5E7EB")
DARK_TEXT = colors.HexColor("#1F2937")
MUTED_TEXT = colors.HexColor("#64748B")
WHITE = colors.white

PAGE_SIZE = A4
MARGIN = 1.5 * cm  # Reduced margin slightly to give more room for layout


def get_logo_drawing(size=32):
    """Draw the corporate hexagon + inner interlocking logo in vector form."""
    d = Drawing(size, size)
    s = size / 32.0
    
    # Outer hexagon path: M16 3L29 10.5V25.5L16 33L3 25.5V10.5L16 3Z
    hex_points = [
        16 * s, (32 - 3) * s,
        29 * s, (32 - 10.5) * s,
        29 * s, (32 - 25.5) * s,
        16 * s, (32 - 33) * s,
        3 * s, (32 - 25.5) * s,
        3 * s, (32 - 10.5) * s
    ]
    hexagon = Polygon(
        hex_points,
        strokeColor=PRIMARY_BLUE,
        strokeWidth=2.5 * s,
        fillColor=None
    )
    
    # Inner interlocking shape: M11 12.5L16 15.5L21 12.5V23.5L16 20.5L11 23.5V12.5Z
    inner_points = [
        11 * s, (32 - 12.5) * s,
        16 * s, (32 - 15.5) * s,
        21 * s, (32 - 12.5) * s,
        21 * s, (32 - 23.5) * s,
        16 * s, (32 - 20.5) * s,
        11 * s, (32 - 23.5) * s
    ]
    inner = Polygon(
        inner_points,
        strokeColor=None,
        fillColor=SUCCESS_GREEN
    )
    
    d.add(hexagon)
    d.add(inner)
    return d


def get_styles():
    """Return a dict of paragraph styles used across generated PDFs."""
    base = getSampleStyleSheet()
    styles = {
        "CoverTitle": ParagraphStyle(
            "CoverTitle", parent=base["Title"], fontSize=24, leading=28,
            textColor=DARK_TEXT, alignment=TA_CENTER, spaceAfter=8,
            fontName="Helvetica-Bold",
        ),
        "CoverSubtitle": ParagraphStyle(
            "CoverSubtitle", parent=base["Normal"], fontSize=12, leading=16,
            textColor=MUTED_TEXT, alignment=TA_CENTER, spaceAfter=4,
        ),
        "SectionHeader": ParagraphStyle(
            "SectionHeader", parent=base["Heading2"], fontSize=12, leading=15,
            textColor=WHITE, backColor=PRIMARY_BLUE, alignment=TA_LEFT,
            spaceBefore=14, spaceAfter=8, borderPadding=(5, 8, 5, 8),
            fontName="Helvetica-Bold",
        ),
        "Body": ParagraphStyle(
            "Body", parent=base["Normal"], fontSize=9, leading=13,
            textColor=DARK_TEXT,
        ),
        "BodyBold": ParagraphStyle(
            "BodyBold", parent=base["Normal"], fontSize=9, leading=13,
            textColor=PRIMARY_BLUE, fontName="Helvetica-Bold",
        ),
    }
    return styles


def styled_table(header_row, data_rows, col_widths=None):
    """Build a Table with the shared primary blue header + alternating row banding."""
    table_data = [header_row] + data_rows
    table = Table(table_data, colWidths=col_widths, repeatRows=1)

    style = [
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY_BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (-1, 0), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]
    for row_index in range(1, len(table_data)):
        bg_color = LIGHT_BG if row_index % 2 == 0 else WHITE
        style.append(("BACKGROUND", (0, row_index), (-1, row_index), bg_color))
        style.append(("TEXTCOLOR", (0, row_index), (-1, row_index), DARK_TEXT))
        style.append(("FONTNAME", (0, row_index), (-1, row_index), "Helvetica"))
    
    table.setStyle(TableStyle(style))
    return table


def footer_canvas(canvas, doc, brand_line="Generated by NutriLens"):
    """Draw the shared footer with brand line + page number on every page."""
    canvas.saveState()
    canvas.setStrokeColor(BORDER_COLOR)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 1.5 * cm, PAGE_SIZE[0] - MARGIN, 1.5 * cm)

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED_TEXT)
    
    # Left Footer text
    left_text = f"{brand_line} • Smart Nutrition Analytics Platform"
    canvas.drawString(MARGIN, 1.1 * cm, left_text)
    
    # Right Footer text
    current_date = datetime.utcnow().strftime('%Y-%m-%d')
    right_text = f"Page {doc.page} • Generated: {current_date}"
    canvas.drawRightString(PAGE_SIZE[0] - MARGIN, 1.1 * cm, right_text)
    
    canvas.restoreState()
